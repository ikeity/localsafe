# Opt-in: creates and uninstalls ONLY a disposable, current-user fictional application.
param([switch]$RunFixture)
if(!$RunFixture){throw 'Use -RunFixture to run the disposable application integration test.'}
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot '..\src\LocalSafe.Uninstall.psm1') -Force
function Assert($Condition,[string]$Message){if(!$Condition){throw $Message}}
$id=[guid]::NewGuid().ToString('N')
$area=Join-Path ([IO.Path]::GetTempPath()) ('LocalSafe-UninstallTest-'+$id)
$name='ExampleApp-'+$id;$root=Join-Path $area $name
$uninstallKey='SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\LocalSafeFixture-'+$id
$productKey='SOFTWARE\LocalSafeFixtures\'+$name
$session=$null
try {
    New-Item -ItemType Directory -Path $root -Force | Out-Null
    $binary=Join-Path $root 'uninstall.exe'
    $code=@'
using System;
using System.IO;
using Microsoft.Win32;
internal static class Fixture {
    [STAThread] private static int Main(string[] args) {
        if (args.Length != 2 || !args[0].StartsWith(@"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\LocalSafeFixture-")) return 10;
        string parent=Path.GetFileName(Path.GetDirectoryName(args[1]));
        if (!parent.StartsWith("LocalSafe-UninstallTest-")) return 11;
        Registry.CurrentUser.DeleteSubKeyTree(args[0], false);
        File.WriteAllText(Path.Combine(args[1], "remaining.txt"), "fictional disposable residue");
        using (RegistryKey k=Registry.CurrentUser.CreateSubKey(@"SOFTWARE\LocalSafeFixtures\"+Path.GetFileName(args[1]))) k.SetValue("InstallPath", args[1]);
        return 0;
    }
}
'@
    Add-Type -TypeDefinition $code -OutputAssembly $binary -OutputType WindowsApplication
    $command='"'+$binary+'" "'+$uninstallKey+'" "'+$root+'"'
    $key=[Microsoft.Win32.Registry]::CurrentUser.CreateSubKey($uninstallKey)
    try{foreach($pair in @{DisplayName=$name;DisplayVersion='1.0';Publisher='ExampleVendor';InstallLocation=$root;UninstallString=$command}.GetEnumerator()){$key.SetValue($pair.Key,$pair.Value)}}finally{$key.Dispose()}
    $program=[pscustomobject]@{Id=('HKEY_CURRENT_USER\'+$uninstallKey);RegistrationIds=@('HKEY_CURRENT_USER\'+$uninstallKey);Name=$name;Version='1.0';Publisher='ExampleVendor';Kind='Desktop';Scope='CurrentUser';InstallPath=$root;PathSource='InstallLocation'}
    $session=New-LSUninstallSession $program -Directory (Join-Path $area 'journal')
    Assert ($session.State -eq 'Prepared') 'Prepare must not launch the uninstaller.'
    Assert (Test-Path -LiteralPath ('Registry::HKEY_CURRENT_USER\'+$uninstallKey)) 'Fixture must still be registered before confirmation.'
    $session=Invoke-LSOfficialUninstall $session -Confirmed
    Assert ($session.ExitCode -eq 0 -and !$session.Review.StillRegistered) 'Fixture uninstaller must remove only its own registration.'
    $items=@($session.Review.Items | Where-Object {$_.CanClean -and $_.Action -in @('QuarantineDirectory','RemoveRegistryKey')})
    Assert ($items.Count -eq 2) ('Expected disposable install folder and product key; got '+$items.Count+' '+($session.Review.Items | ConvertTo-Json -Depth 4))
    $session=Invoke-LSResidualCleanup $session -SelectedIds @($items.Id) -Confirmed
    Assert (!(Test-Path -LiteralPath $root)) 'Confirmed install folder must be quarantined.'
    Assert (!(Test-Path -LiteralPath ('Registry::HKEY_CURRENT_USER\'+$productKey))) 'Only the fixture product key must be removed.'
    $quarantine=@($session.Operations | Where-Object {$_.Status -eq 'Quarantined'})[0].Quarantine
    Assert (Test-Path -LiteralPath (Join-Path $quarantine 'remaining.txt')) 'Quarantine must preserve file contents.'
    Assert (@($session.Operations | Where-Object {$_.Status -eq 'Failed'}).Count -eq 0) 'No operation should be falsely marked successful.'
    Assert (@($session.Review.Items | Where-Object {$_.CanClean}).Count -eq 0) 'Fresh post-cleanup review must confirm fixture removal.'
    Assert ($session.Verdict.CheckedAt -eq $session.Review.CapturedAt) 'Persist the verdict together with the exact review shown by the UI.'
    Assert (@(Get-ChildItem -LiteralPath $session.Folder -Filter '*.reg' -Recurse).Count -eq 1) 'Product registration must be backed up.'
    'PASS: real fixture EXE uninstall -> fresh residue review -> confirmed registry backup/removal and reversible directory quarantine -> fresh verification.'
} finally {
    # These exact HKCU keys are exclusively generated by this test.
    [Microsoft.Win32.Registry]::CurrentUser.DeleteSubKeyTree($uninstallKey,$false)
    [Microsoft.Win32.Registry]::CurrentUser.DeleteSubKeyTree($productKey,$false)
    $resolved=[IO.Path]::GetFullPath($area).TrimEnd('\')
    $temp=[IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\')
    if([IO.Path]::GetDirectoryName($resolved) -ine $temp -or [IO.Path]::GetFileName($resolved) -cne ('LocalSafe-UninstallTest-'+$id)){throw 'Refusing to remove a test path outside its generated temp directory.'}
    if(Test-Path -LiteralPath $resolved){Remove-Item -LiteralPath $resolved -Recurse -Force}
}
